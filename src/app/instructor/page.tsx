'use client';

import React, { useState } from 'react';
import Link from 'next/link';
import { MOCK_COURSES, MOCK_LESSONS } from '@/lib/mockData';

export default function InstructorStudioPage() {
  const [modules, setModules] = useState(MOCK_LESSONS);
  const [newModuleTitle, setNewModuleTitle] = useState('');
  const [generatedQuiz, setGeneratedQuiz] = useState<string | null>(null);

  const handleAddModule = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newModuleTitle.trim()) return;

    const newMod = {
      id: `les-${Date.now()}`,
      courseId: MOCK_COURSES[0].id,
      title: newModuleTitle,
      order: modules.length + 1,
      durationMinutes: 25,
      videoUrl: 'https://commondatastorage.googleapis.com/gtv-videos-bucket/sample/BigBuckBunny.mp4',
      transcript: 'Transcript will be generated automatically upon DRM encoding.',
      summary: 'Summary generated by NEXA Pedagogical Engine.',
      quizQuestions: [],
    };

    setModules([...modules, newMod]);
    setNewModuleTitle('');
  };

  const handleGenerateQuiz = () => {
    setGeneratedQuiz(
      `✓ 3 Questions Generated for '${modules[0].title}':\n1. Explain the CAP theorem tradeoffs under Raft.\n2. How does randomized timeout prevent split-votes?\n3. What is the role of log compaction in state-machine snapshotting?`
    );
  };

  return (
    <div className="w-full pt-16 flex flex-col bg-surface min-h-screen">
      {/* Header */}
      <section className="bg-surface-container-lowest border-b border-outline-variant/30 py-6 px-4 sm:px-6 lg:px-8">
        <div className="mx-auto max-w-7xl flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <div className="flex items-center gap-2 mb-1">
              <span className="text-xs font-mono uppercase tracking-wider text-secondary font-bold">
                Curriculum Studio
              </span>
              <span className="text-xs font-mono bg-surface-container px-2 py-0.5 rounded-full text-on-surface-variant">
                Instructor Tier-1
              </span>
            </div>
            <h1 className="font-headline text-2xl font-bold text-on-surface">
              {MOCK_COURSES[0].title}
            </h1>
            <p className="text-xs text-on-surface-variant">
              Enrolled: <strong>{MOCK_COURSES[0].enrolledStudents} Students</strong> • Rating: <strong>★ {MOCK_COURSES[0].rating}</strong>
            </p>
          </div>

          <div className="flex items-center gap-3">
            <Link
              href="/app/nexa"
              className="flex items-center gap-2 px-4 py-2 rounded-xl bg-slate-900 border border-cyan-500/40 text-cyan-300 hover:bg-slate-800 text-xs font-mono font-bold transition-all shadow-quantum-subtle"
            >
              <span className="material-symbols-outlined text-sm">psychology</span>
              <span>Ask NEXA to Audit Course</span>
            </Link>
            <button
              type="button"
              className="px-4 py-2 rounded-xl bg-secondary text-white text-xs font-bold hover:bg-blue-700 transition-colors shadow-sm"
            >
              Publish Updated Syllabus
            </button>
          </div>
        </div>
      </section>

      {/* Main 2-Column Split: Module Builder & AI Assessment Studio */}
      <div className="mx-auto max-w-7xl w-full px-4 sm:px-6 lg:px-8 py-8 flex-1 grid grid-cols-1 lg:grid-cols-12 gap-8">
        {/* Module Builder (7 Cols) */}
        <div className="lg:col-span-7 flex flex-col gap-4">
          <div className="flex items-center justify-between">
            <h2 className="font-headline text-base font-bold text-on-surface">
              Curriculum Modules ({modules.length})
            </h2>
            <span className="text-xs font-mono text-on-surface-variant">
              DRM Encrypted &amp; Watermarked
            </span>
          </div>

          <div className="space-y-3">
            {modules.map((mod, idx) => (
              <div
                key={mod.id}
                className="p-4 rounded-xl bg-surface-container-lowest border border-outline-variant/30 shadow-sm flex items-center justify-between gap-4"
              >
                <div className="flex items-center gap-3">
                  <div className="w-8 h-8 rounded-lg bg-surface-container flex items-center justify-center font-mono font-bold text-xs text-secondary">
                    {idx + 1}
                  </div>
                  <div>
                    <h3 className="font-title text-sm font-bold text-on-surface">
                      {mod.title}
                    </h3>
                    <p className="text-xs text-on-surface-variant">
                      {mod.durationMinutes} mins • DRM Protected
                    </p>
                  </div>
                </div>

                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    className="p-1.5 text-on-surface-variant hover:text-secondary rounded"
                  >
                    <span className="material-symbols-outlined text-base">edit</span>
                  </button>
                  <Link
                    href="/lms/player"
                    className="p-1.5 text-secondary hover:text-blue-800 rounded"
                  >
                    <span className="material-symbols-outlined text-base">play_circle</span>
                  </Link>
                </div>
              </div>
            ))}
          </div>

          {/* Add Module Form */}
          <form
            onSubmit={handleAddModule}
            className="p-4 rounded-xl bg-surface-container-low border border-dashed border-outline-variant/40 flex items-center gap-3 mt-2"
          >
            <input
              type="text"
              value={newModuleTitle}
              onChange={(e) => setNewModuleTitle(e.target.value)}
              placeholder="Module Title, e.g. 'Module 3: Log Replication Under Partitions'..."
              className="flex-1 bg-surface-container-lowest border border-outline-variant/30 rounded-lg px-3 py-2 text-xs text-on-surface focus:outline-none"
            />
            <button
              type="submit"
              className="px-4 py-2 rounded-lg bg-secondary text-white text-xs font-bold hover:bg-blue-700 transition-colors shadow-xs"
            >
              + Add Module
            </button>
          </form>
        </div>

        {/* AI Quiz & Analytics Studio (5 Cols) */}
        <div className="lg:col-span-5 flex flex-col gap-6">
          {/* AI Assessment Generator */}
          <div className="rounded-2xl bg-surface-container-lowest border border-outline-variant/30 p-5 shadow-sm space-y-3">
            <div className="flex items-center justify-between border-b border-outline-variant/20 pb-3">
              <span className="text-xs font-mono uppercase tracking-wider text-secondary font-bold">
                NEXA Pedagogical Studio
              </span>
              <span className="material-symbols-outlined text-base text-secondary">auto_awesome</span>
            </div>

            <h3 className="font-title text-sm font-bold text-on-surface">
              Synthesize Interactive Assessment
            </h3>
            <p className="text-xs text-on-surface-variant leading-relaxed">
              NEXA parses the video transcript and syllabus to formulate balanced conceptual and code quiz questions.
            </p>

            <button
              type="button"
              onClick={handleGenerateQuiz}
              className="w-full py-2.5 rounded-xl bg-slate-900 text-cyan-300 border border-cyan-500/40 text-xs font-mono font-bold hover:bg-slate-800 transition-colors flex items-center justify-center gap-2"
            >
              <span className="material-symbols-outlined text-sm">psychology</span>
              <span>Generate Quiz Questions</span>
            </button>

            {generatedQuiz && (
              <div className="p-3 rounded-lg bg-slate-950 text-cyan-200 font-mono text-xs whitespace-pre-wrap border border-cyan-500/30">
                {generatedQuiz}
              </div>
            )}
          </div>

          {/* Student Performance Analytics */}
          <div className="rounded-2xl bg-surface-container-lowest border border-outline-variant/30 p-5 shadow-sm space-y-3">
            <h3 className="font-title text-sm font-bold text-on-surface">
              Student Retention &amp; Drop-off Analysis
            </h3>
            <div className="space-y-2 text-xs">
              <div className="flex justify-between">
                <span className="text-on-surface-variant">Module 1 Completion:</span>
                <span className="font-mono font-bold text-emerald-600">92%</span>
              </div>
              <div className="flex justify-between">
                <span className="text-on-surface-variant">Module 2 Quiz Pass Rate:</span>
                <span className="font-mono font-bold text-secondary">78%</span>
              </div>
              <div className="flex justify-between">
                <span className="text-on-surface-variant">Flagged Bottleneck:</span>
                <span className="font-mono font-bold text-amber-600">FLP Proof (Re-quiz recommended)</span>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}

